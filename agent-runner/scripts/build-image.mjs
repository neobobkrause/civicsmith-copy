#!/usr/bin/env node
/* Build what the image carries (R56, R26): `dist/image/entry.js`, the server that listens at once, and the run it loads
 * after listening (`dist/image/chunks/run.js`), each one self-contained file with `ai-gate` and the plane modules it
 * reads bundled in (the image cannot reach the repository), and no package of `node_modules`. The plane's word table
 * (`setup-words/rows.mjs`) is left out: the image reads its own carried rows (R41), and a `localize` inside a bundled
 * module answers its code's own sentence. The output is built at test, deploy and release, never committed;
 * the image's Dockerfile copies `dist/image/` and nothing else. Deterministic: the same sources give the same bytes.
 *
 * Run from the repository root: node agent-runner/scripts/build-image.mjs [--check]
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, relative } from 'node:path';
import { createRequire } from 'node:module';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const OUTDIR = here('../dist/image');
const require = createRequire(here('../../bio-plane/package.json'));

// The word table's rows, replaced in the image by an empty table (R41: the image carries its own rows).
const noWordTable = {
  name: 'no-word-table',
  setup(b) {
    b.onResolve({ filter: /^\.\/rows\.mjs$/ }, (a) => (/setup-words[\\/]index\.mjs$/.test(a.importer) ? { path: 'rows', namespace: 'no-word-table' } : undefined));
    b.onLoad({ filter: /.*/, namespace: 'no-word-table' }, () => ({ contents: 'export const WORD_ROWS = Object.freeze([]); export const WORDS_COMMIT = null;', loader: 'js' }));
  },
};

export async function buildImage() {
  const esbuild = require('esbuild');
  const out = await esbuild.build({
    entryPoints: [here('../src/entry.mjs')], bundle: true, splitting: true, format: 'esm', platform: 'node', target: 'node22',
    absWorkingDir: here('../..'), outdir: OUTDIR, chunkNames: 'chunks/[name]', write: false, legalComments: 'none', logLevel: 'silent', plugins: [noWordTable],
    banner: { js: '// GENERATED by agent-runner/scripts/build-image.mjs from agent-runner/src (R56). Do not edit.' },
  });
  return out.outputFiles.map((f) => ({ path: relative(OUTDIR, f.path), text: f.text })).sort((a, b) => (a.path < b.path ? -1 : 1));
}

const listed = (dir, base = dir) => (existsSync(dir) ? readdirSync(dir, { withFileTypes: true }).flatMap((e) =>
  (e.isDirectory() ? listed(join(dir, e.name), base) : [relative(base, join(dir, e.name))])) : []).sort();

export async function staleFiles() {
  const files = await buildImage();
  const faults = [];
  const now = listed(OUTDIR);
  for (const f of files) {
    let had = null;
    try { had = readFileSync(join(OUTDIR, f.path), 'utf8'); } catch { /* missing */ }
    if (had !== f.text) faults.push(f.path);
  }
  for (const p of now) if (!files.some((f) => f.path === p)) faults.push(p);
  return faults;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    const s = await staleFiles();
    if (s.length) { console.error(`agent-runner/dist/image is stale (${s.join(', ')}): run node agent-runner/scripts/build-image.mjs`); process.exit(1); }
  } else {
    const files = await buildImage();
    rmSync(OUTDIR, { recursive: true, force: true });
    for (const f of files) { mkdirSync(join(OUTDIR, f.path, '..'), { recursive: true }); writeFileSync(join(OUTDIR, f.path), f.text); }
    console.log(`agent-runner: wrote ${files.map((f) => `dist/image/${f.path} (${f.text.length} B)`).join(', ')}`);
  }
}
